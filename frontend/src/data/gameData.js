// Helper function to get questions by difficulty
export const getQuestionsByDifficulty = (difficulty) => {
  return triviaQuestions.filter(q => q.difficulty === difficulty);
};

// Helper function to get mixed difficulty questions for a round (30 questions)
export const getRoundQuestions = (roundNumber = 1) => {
  const easy = getQuestionsByDifficulty('easy');
  const medium = getQuestionsByDifficulty('medium');
  const hard = getQuestionsByDifficulty('hard');
  
  // Progressive difficulty based on round
  let easyCount, mediumCount, hardCount;
  
  if (roundNumber <= 3) {
    // Early rounds: more easy
    easyCount = 15;
    mediumCount = 10;
    hardCount = 5;
  } else if (roundNumber <= 6) {
    // Middle rounds: balanced
    easyCount = 10;
    mediumCount = 12;
    hardCount = 8;
  } else {
    // Later rounds: more hard
    easyCount = 5;
    mediumCount = 10;
    hardCount = 15;
  }
  
  // Shuffle and pick
  const shuffleArray = (arr) => [...arr].sort(() => Math.random() - 0.5);
  
  const selectedEasy = shuffleArray(easy).slice(0, easyCount);
  const selectedMedium = shuffleArray(medium).slice(0, mediumCount);
  const selectedHard = shuffleArray(hard).slice(0, hardCount);
  
  // Combine and shuffle
  return shuffleArray([...selectedEasy, ...selectedMedium, ...selectedHard]);
};

