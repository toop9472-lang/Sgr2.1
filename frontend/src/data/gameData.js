// Speed Math - Difficulty Levels
export const mathOperations = {
  easy: ['+', '-'],
  medium: ['+', '-', '*'],
  hard: ['+', '-', '*', '/']
};

// Generate random math problem
export const generateMathProblem = (difficulty = 'medium') => {
  const ops = mathOperations[difficulty] || mathOperations.medium;
  const op = ops[Math.floor(Math.random() * ops.length)];
  
  let num1, num2, answer;
  
  switch(difficulty) {
    case 'easy':
      num1 = Math.floor(Math.random() * 20) + 1;
      num2 = Math.floor(Math.random() * 20) + 1;
      break;
    case 'hard':
      num1 = Math.floor(Math.random() * 50) + 10;
      num2 = Math.floor(Math.random() * 30) + 5;
      break;
    default: // medium
      num1 = Math.floor(Math.random() * 30) + 5;
      num2 = Math.floor(Math.random() * 20) + 1;
  }
  
  // Ensure division results in whole numbers
  if (op === '/') {
    num1 = num2 * (Math.floor(Math.random() * 10) + 1);
  }
  
  // Ensure subtraction doesn't give negative
  if (op === '-' && num2 > num1) {
    [num1, num2] = [num2, num1];
  }
  
  switch(op) {
    case '+': answer = num1 + num2; break;
    case '-': answer = num1 - num2; break;
    case '*': answer = num1 * num2; break;
    case '/': answer = num1 / num2; break;
    default: answer = num1 + num2;
  }
  
  // Generate wrong options
  const options = [answer];
  while (options.length < 4) {
    const wrongAnswer = answer + (Math.floor(Math.random() * 20) - 10);
    if (wrongAnswer !== answer && wrongAnswer > 0 && !options.includes(wrongAnswer)) {
      options.push(Math.round(wrongAnswer));
    }
  }
  
  // Shuffle options
  const shuffled = options.sort(() => Math.random() - 0.5);
  
  return {
    question: `${num1} ${op} ${num2} = ?`,
    num1,
    num2,
    operator: op,
    answer,
    options: shuffled,
    correctIndex: shuffled.indexOf(answer)
  };
};

